def cycle(time: int=0, tomato_style: int=0) -> None:
    for i in range(len(tomatoes[tomato_style])):
        print("\033[2J\033[H", end="") # Clear Screen
        print(tomatoes[tomato_style][i])
        print(f"       Time: {time}")
        stdout.flush()
        sleep(1)
        time-=1
